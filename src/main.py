"""Generate an Angular client from swagger.json.

The output mirrors swagger-codegen (typescript-angular) layout:

    output/
      api/<tag>.service.ts, api/api.ts
      model/<name>.ts, model/models.ts
      api.module.ts, index.ts
      configuration.ts, encoder.ts, variables.ts, ... (copied from src/templates)
"""
import json
import os
import re
import shutil

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INPUT_FILE = os.path.join(BASE_DIR, "input", "swagger.json")
OUTPUT_ROOT = os.path.join(BASE_DIR, "output")
OUTPUT_DIR = OUTPUT_ROOT  # set in main() to output/<swagger title>
TEMPLATES_DIR = os.path.join(BASE_DIR, "src", "templates")
API_DIR = os.path.join(OUTPUT_DIR, "api")
MODELS_DIR = os.path.join(OUTPUT_DIR, "model")

NL = "\r\n"  # swagger-codegen output on Windows uses CRLF

STATIC_FILES = ["configuration.ts", "encoder.ts", "variables.ts"]


# ---------------------------------------------------------------- helpers

def write_file(path, text):
    """Write text (using \\n internally) with CRLF line endings."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(text.replace("\n", NL).encode("utf-8"))


def lower_first(name):
    return name[:1].lower() + name[1:]


def upper_first(name):
    return name[:1].upper() + name[1:]


def header_comment(info):
    title = info.get("title", "")
    version = info.get("version", "")
    return (
        "/**\n"
        f" * {title}\n"
        " *\n"
        f" * OpenAPI spec version: {version}\n"
        " * \n"
        " *\n"
        " * NOTE: This class is auto generated by the swagger code generator program.\n"
        " * Do not edit the class manually.\n"
        " */"
    )


def ref_name(ref):
    return ref.split("/")[-1]


def schema_ref(schema):
    """Return referenced schema name for $ref / allOf[$ref] else None."""
    if not isinstance(schema, dict):
        return None
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    for key in ("allOf", "oneOf", "anyOf"):
        items = schema.get(key)
        if isinstance(items, list) and items and "$ref" in items[0]:
            return ref_name(items[0]["$ref"])
    return None


def ts_type(schema):
    """OpenAPI schema -> TypeScript type (swagger-codegen style)."""
    if not schema:
        return "any"
    ref = schema_ref(schema)
    if ref:
        return ref
    t = schema.get("type")
    fmt = schema.get("format")
    if t == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "string":
        if fmt in ("date", "date-time"):
            return "Date"
        if fmt == "binary":
            return "Blob"
        return "string"
    if t == "object" or "additionalProperties" in schema:
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"{{ [key: string]: {ts_type(ap)}; }}"
        return "any"
    return "any"


def referenced_models(schema):
    """All schema names referenced anywhere inside a schema (for imports)."""
    found = set()
    if isinstance(schema, dict):
        for k, v in schema.items():
            if k == "$ref" and isinstance(v, str):
                found.add(ref_name(v))
            else:
                found |= referenced_models(v)
    elif isinstance(schema, list):
        for v in schema:
            found |= referenced_models(v)
    return found


def param_name(name):
    """HTTP header / query name -> camelCase identifier (X-From-Channel -> xFromChannel)."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", name) if p]
    if not parts:
        return name
    first = parts[0]
    result = first[:1].lower() + first[1:]
    for p in parts[1:]:
        result += p[:1].upper() + p[1:]
    return result


def operation_id(method, path):
    """/Amending/CompanyId/{companyId}/Detail + get -> amendingCompanyIdCompanyIdDetailGet."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", path) if p]
    name = "".join(upper_first(p) for p in parts)
    return lower_first(name) + upper_first(method.lower())


# ----------------------------------------------------------------- models

def enum_member_name(value):
    text = str(value)
    if isinstance(value, (int, float)):
        text = ("NUMBER_" + text).replace("-", "MINUS_")
        return text.replace(".", "_")
    name = re.sub(r"[^0-9A-Za-z]+", "_", text).strip("_").upper()
    return name or "EMPTY"


def generate_model(name, schema, header):
    out = header + "\n"
    if "enum" in schema:
        values = schema["enum"]
        if schema.get("type") in ("integer", "number"):
            literals = [str(v) for v in values]
        else:
            literals = [f"'{v}'" for v in values]
        out += "\n"
        if schema.get("description"):
            out += f"/**\n * {schema['description']}\n */\n"
        out += f"export type {name} = {' | '.join(literals)};\n\n"
        out += f"export const {name} = {{\n"
        members = []
        for v, lit in zip(values, literals):
            members.append(f"    {enum_member_name(v)}: {lit} as {name}")
        out += ",\n".join(members) + "\n};"
        return out

    props = schema.get("properties", {}) or {}
    required = schema.get("required", []) or []

    imports = sorted(referenced_models(props) - {name})
    for imp in imports:
        out += f"import {{ {imp} }} from './{lower_first(imp)}';\n"
    out += "\n"

    if schema.get("description"):
        out += f"/**\n * {schema['description']}\n */\n"
    out += f"export interface {name} {{ \n"
    for prop_name, prop in props.items():
        description = prop.get("description")
        if description:
            out += f"    /**\n     * {description}\n     */\n"
        optional = "" if prop_name in required else "?"
        out += f"    {prop_name}{optional}: {ts_type(prop)};\n"
    out += "}"
    return out


def generate_models(swagger):
    schemas = swagger.get("components", {}).get("schemas", {})
    header = header_comment(swagger.get("info", {}))
    names = list(schemas.keys())
    for name in names:
        write_file(os.path.join(MODELS_DIR, f"{lower_first(name)}.ts"),
                   generate_model(name, schemas[name], header))
    index = "".join(f"export * from './{lower_first(n)}';\n" for n in sorted(names))
    write_file(os.path.join(MODELS_DIR, "models.ts"), index)
    print(f"Generated {len(names)} models in {MODELS_DIR}")


# --------------------------------------------------------------- services

class Param:
    def __init__(self, raw_name, ident, ts, required, location, description):
        self.raw_name = raw_name
        self.ident = ident
        self.ts = ts
        self.required = required
        self.location = location
        self.description = description or ""


def collect_params(operation):
    params = []
    body = operation.get("requestBody")
    body_param = None
    if body:
        content = body.get("content", {})
        media = content.get("application/json") or next(iter(content.values()), {})
        body_param = Param("body", "body", ts_type(media.get("schema", {})),
                           bool(body.get("required")), "body", body.get("description"))
    for p in operation.get("parameters", []):
        params.append(Param(p["name"], param_name(p["name"]), ts_type(p.get("schema", {})),
                            bool(p.get("required")), p.get("in"), p.get("description")))
    if body_param:
        params.insert(0, body_param)
    # required parameters first (stable), like swagger-codegen's sortParamsByRequiredFlag
    return [p for p in params if p.required] + [p for p in params if not p.required]


def response_type(operation):
    responses = operation.get("responses", {})
    resp = responses.get("200") or responses.get("201")
    if resp and "content" in resp:
        content = resp["content"]
        media = content.get("application/json") or next(iter(content.values()), {})
        return ts_type(media.get("schema", {}))
    return "any"


def has_response_content(operation):
    return any("content" in r for r in operation.get("responses", {}).values())


def generate_operation(path, method, operation):
    op_id = operation_id(method, path)
    params = collect_params(operation)
    ret = response_type(operation)
    summary = operation.get("summary", "") or ""
    notes = operation.get("description", "") or ""

    out = "    /**\n"
    out += f"     * {summary}\n"
    out += f"     * {notes}\n"
    out += "     * \n" if False else ""
    for p in params:
        out += f"     * @param {p.ident} {p.description}\n"
    out += "     * @param observe set whether or not to return the data Observable as the body, response or events. defaults to returning the body.\n"
    out += "     * @param reportProgress flag to report request and response progress.\n"
    out += "     */\n"

    sig = "".join(f"{p.ident}{'' if p.required else '?'}: {p.ts}, " for p in params)
    out += f"    public {op_id}({sig}observe?: 'body', reportProgress?: boolean): Observable<{ret}>;\n"
    out += f"    public {op_id}({sig}observe?: 'response', reportProgress?: boolean): Observable<HttpResponse<{ret}>>;\n"
    out += f"    public {op_id}({sig}observe?: 'events', reportProgress?: boolean): Observable<HttpEvent<{ret}>>;\n"
    out += f"    public {op_id}({sig}observe: any = 'body', reportProgress: boolean = false ): Observable<any> {{\n"

    required = [p for p in params if p.required]
    query = [p for p in params if p.location == "query"]
    headers = [p for p in params if p.location == "header"]
    paths = [p for p in params if p.location == "path"]
    has_body = any(p.location == "body" for p in params)

    # swagger-codegen's template leaves one blank line per optional query/body parameter
    blanks = 5 + (1 if has_body else 0) + len([p for p in query if not p.required])
    if required:
        out += "\n"
    for i, p in enumerate(required):
        if i:
            out += "\n"
        out += f"        if ({p.ident} === null || {p.ident} === undefined) {{\n"
        out += f"            throw new Error('Required parameter {p.ident} was null or undefined when calling {op_id}.');\n"
        out += "        }\n"
    out += "\n" * blanks

    if query:
        out += "        let queryParameters = new HttpParams({encoder: new CustomHttpUrlEncodingCodec()});\n"
        for p in query:
            out += f"        if ({p.ident} !== undefined && {p.ident} !== null) {{\n"
            out += f"            queryParameters = queryParameters.set('{p.raw_name}', <any>{p.ident});\n"
            out += "        }\n"
        out += "\n"

    out += "        let headers = this.defaultHeaders;\n"
    for p in headers:
        out += f"        if ({p.ident} !== undefined && {p.ident} !== null) {{\n"
        out += f"            headers = headers.set('{p.raw_name}', String({p.ident}));\n"
        out += "        }\n"

    out += "\n"
    out += "        // authentication (Bearer) required\n"
    out += "        if (this.configuration.apiKeys && this.configuration.apiKeys[\"Authorization\"]) {\n"
    out += "            headers = headers.set('Authorization', this.configuration.apiKeys[\"Authorization\"]);\n"
    out += "        }\n\n"
    out += "        // to determine the Accept header\n"
    out += "        let httpHeaderAccepts: string[] = [\n"
    if has_response_content(operation):
        out += "            'text/plain',\n"
        out += "            'application/json',\n"
        out += "            'text/json'\n"
    out += "        ];\n"
    out += "        const httpHeaderAcceptSelected: string | undefined = this.configuration.selectHeaderAccept(httpHeaderAccepts);\n"
    out += "        if (httpHeaderAcceptSelected != undefined) {\n"
    out += "            headers = headers.set('Accept', httpHeaderAcceptSelected);\n"
    out += "        }\n\n"
    out += "        // to determine the Content-Type header\n"
    out += "        const consumes: string[] = [\n"
    if has_body:
        out += "            'application/json',\n"
        out += "            'text/json',\n"
        out += "            'application/_*+json'\n"
    out += "        ];\n"
    if has_body:
        out += "        const httpContentTypeSelected: string | undefined = this.configuration.selectHeaderContentType(consumes);\n"
        out += "        if (httpContentTypeSelected != undefined) {\n"
        out += "            headers = headers.set('Content-Type', httpContentTypeSelected);\n"
        out += "        }\n"
    out += "\n"

    url = path
    for p in paths:
        url = url.replace("{" + p.raw_name + "}", "${encodeURIComponent(String(" + p.ident + "))}")
    out += f"        return this.httpClient.request<{ret}>('{method.lower()}',`${{this.basePath}}{url}`,\n"
    out += "            {\n"
    if has_body:
        out += "                body: body,\n"
    if query:
        out += "                params: queryParameters,\n"
    out += "                withCredentials: this.configuration.withCredentials,\n"
    out += "                headers: headers,\n"
    out += "                observe: observe,\n"
    out += "                reportProgress: reportProgress\n"
    out += "            }\n"
    out += "        );\n"
    out += "    }\n\n"
    return out


def service_class_name(tag):
    return upper_first(tag) + "Service"


def generate_service(tag, operations, header):
    imports = set()
    for path, method, op in operations:
        imports |= referenced_models(op.get("requestBody", {}))
        for p in op.get("parameters", []):
            imports |= referenced_models(p.get("schema", {}))
        imports |= referenced_models(op.get("responses", {}))

    out = header
    out += "/* tslint:disable:no-unused-variable member-ordering */\n\n"
    out += "import { Inject, Injectable, Optional }                      from '@angular/core';\n"
    out += "import { HttpClient, HttpHeaders, HttpParams,\n"
    out += "         HttpResponse, HttpEvent }                           from '@angular/common/http';\n"
    out += "import { CustomHttpUrlEncodingCodec }                        from '../encoder';\n\n"
    out += "import { Observable }                                        from 'rxjs';\n\n"
    for imp in sorted(imports):
        out += f"import {{ {imp} }} from '../model/{lower_first(imp)}';\n"
    out += "\n"
    out += "import { BASE_PATH, COLLECTION_FORMATS }                     from '../variables';\n"
    out += "import { Configuration }                                     from '../configuration';\n\n\n"
    out += "@Injectable()\n"
    out += f"export class {service_class_name(tag)} {{\n\n"
    out += "    protected basePath = '/';\n"
    out += "    public defaultHeaders = new HttpHeaders();\n"
    out += "    public configuration = new Configuration();\n\n"
    out += "    constructor(protected httpClient: HttpClient, @Optional()@Inject(BASE_PATH) basePath: string, @Optional() configuration: Configuration) {\n"
    out += "        if (basePath) {\n"
    out += "            this.basePath = basePath;\n"
    out += "        }\n"
    out += "        if (configuration) {\n"
    out += "            this.configuration = configuration;\n"
    out += "            this.basePath = basePath || configuration.basePath || this.basePath;\n"
    out += "        }\n"
    out += "    }\n\n"
    out += "    /**\n"
    out += "     * @param consumes string[] mime-types\n"
    out += "     * @return true: consumes contains 'multipart/form-data', false: otherwise\n"
    out += "     */\n"
    out += "    private canConsumeForm(consumes: string[]): boolean {\n"
    out += "        const form = 'multipart/form-data';\n"
    out += "        for (const consume of consumes) {\n"
    out += "            if (form === consume) {\n"
    out += "                return true;\n"
    out += "            }\n"
    out += "        }\n"
    out += "        return false;\n"
    out += "    }\n\n\n"
    for path, method, op in operations:
        out += generate_operation(path, method, op)
    out += "}\n"
    return out


def generate_services(swagger):
    header = header_comment(swagger.get("info", {}))
    by_tag = {}
    for path, item in swagger.get("paths", {}).items():
        for method, op in item.items():
            if method not in ("get", "put", "post", "delete", "options", "head", "patch"):
                continue
            tag = (op.get("tags") or ["Default"])[0]
            by_tag.setdefault(tag, []).append((path, method, op))

    tags = sorted(by_tag)
    for tag in tags:
        by_tag[tag].sort(key=lambda o: operation_id(o[1], o[0]))
    for tag in tags:
        write_file(os.path.join(API_DIR, f"{lower_first(tag)}.service.ts"),
                   generate_service(tag, by_tag[tag], header))

    api_index = ""
    for tag in tags:
        api_index += f"export * from './{lower_first(tag)}.service';\n"
        api_index += f"import {{ {service_class_name(tag)} }} from './{lower_first(tag)}.service';\n"
    api_index += "export const APIS = [" + ", ".join(service_class_name(t) for t in tags) + "];\n"
    write_file(os.path.join(API_DIR, "api.ts"), api_index)

    module = "import { NgModule, ModuleWithProviders, SkipSelf, Optional } from '@angular/core';\n"
    module += "import { Configuration } from './configuration';\n"
    module += "import { HttpClient } from '@angular/common/http';\n\n\n"
    for tag in tags:
        module += f"import {{ {service_class_name(tag)} }} from './api/{lower_first(tag)}.service';\n"
    module += "\n@NgModule({\n  imports:      [],\n  declarations: [],\n  exports:      [],\n  providers: [\n"
    module += ",\n".join(f"    {service_class_name(t)}" for t in tags) + " ]\n})\n"
    module += (
        "export class ApiModule {\n"
        "    public static forRoot(configurationFactory: () => Configuration): ModuleWithProviders<ApiModule> {\n"
        "        return {\n"
        "            ngModule: ApiModule,\n"
        "            providers: [ { provide: Configuration, useFactory: configurationFactory } ]\n"
        "        };\n"
        "    }\n\n"
        "    constructor( @Optional() @SkipSelf() parentModule: ApiModule,\n"
        "                 @Optional() http: HttpClient) {\n"
        "        if (parentModule) {\n"
        "            throw new Error('ApiModule is already loaded. Import in your base AppModule only.');\n"
        "        }\n"
        "        if (!http) {\n"
        "            throw new Error('You need to import the HttpClientModule in your AppModule! \\n' +\n"
        "            'See also https://github.com/angular/angular/issues/20575');\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    write_file(os.path.join(OUTPUT_DIR, "api.module.ts"), module)

    index = ("export * from './api/api';\nexport * from './model/models';\n"
             "export * from './variables';\nexport * from './configuration';\nexport * from './api.module';")
    write_file(os.path.join(OUTPUT_DIR, "index.ts"), index)
    print(f"Generated {len(tags)} services in {API_DIR}")


def copy_static_files():
    for name in STATIC_FILES:
        shutil.copyfile(os.path.join(TEMPLATES_DIR, name), os.path.join(OUTPUT_DIR, name))


def set_output_dir(title):
    """Point all output paths at output/<swagger title>."""
    global OUTPUT_DIR, API_DIR, MODELS_DIR
    folder = re.sub(r'[<>:"/\|?*]', "_", title or "").strip(" .") or "api"
    OUTPUT_DIR = os.path.join(OUTPUT_ROOT, folder)
    API_DIR = os.path.join(OUTPUT_DIR, "api")
    MODELS_DIR = os.path.join(OUTPUT_DIR, "model")


def main():
    if not os.path.exists(INPUT_FILE):
        print(f"Error: Input file not found at {INPUT_FILE}")
        return
    with open(INPUT_FILE, "r", encoding="utf-8") as f:
        swagger = json.load(f)

    set_output_dir(swagger.get("info", {}).get("title"))
    if os.path.exists(OUTPUT_DIR):
        shutil.rmtree(OUTPUT_DIR)
    os.makedirs(OUTPUT_DIR)

    generate_models(swagger)
    generate_services(swagger)
    copy_static_files()
    print(f"Done. Output: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
